/**
 * Local OCR — REAL PaddleOCR inference test (Mac / .venv-ocr only).
 *
 * The stub suite (scripts/ocr-test.mjs) proves the whole Node<->Python<->pipeline contract
 * WITHOUT paddle, so it runs anywhere. This test is its counterpart: it launches the SAME
 * server/ocr/ocr_service.py with the REAL engine (OCR_ENGINE=paddle) on the operator's
 * .venv-ocr and proves that actual glyph recognition works and that the recognised text
 * flows through the existing retrieval pipeline. It is deliberately kept OUT of `npm test`
 * (heavy, platform-specific, first run may build/download the model) and is wired to
 * `npm run ocr:test:real`.
 *
 * It reads the committed, pre-rendered fixtures (tests/fixtures/ocr/sample-scan.{png,pdf} —
 * regenerated by scripts/make-ocr-fixtures.py if missing) so the recognised tokens are the
 * same pixels everywhere. Covers the spec's Mac-only OCR tests:
 *   A  /health reports engine=paddle, available=true, and a paddleocr version.
 *   C  a scanned IMAGE: real PaddleOCR reads the fixture tokens off sample-scan.png
 *      (through the real Node adapter, server/documents/ocr.mjs).
 *   D  a scanned PDF: POST /ocr/pdf renders sample-scan.pdf (pypdfium2) and OCRs every
 *      page — tokens from BOTH pages are recognised.
 *   E  mixed -> pipeline: the REAL OCR text is ingested as a source:'ocr' page beside a
 *      native page; the document is 'mixed' and the OCR-only topic is retrievable and
 *      tagged ocr/mixed — i.e. real recognition merges into the same index/AI flow.
 *
 * If paddle is not importable here (e.g. run off-Mac, or before `pip install paddleocr`),
 * it prints a clear SKIP and exits 0 — it never fakes a pass.
 *
 *   npm run ocr:test:real
 */

import { spawn, spawnSync } from 'node:child_process';
import { existsSync, mkdtempSync, readFileSync, rmSync } from 'node:fs';
import http from 'node:http';
import { tmpdir } from 'node:os';
import { dirname, isAbsolute, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { setTimeout as sleep } from 'node:timers/promises';

import { loadConfig } from '../server/documents/config.mjs';
import { ocrHealth, ocrImage } from '../server/documents/ocr.mjs';
import { openDocumentStore } from '../server/documents/store.mjs';
import { ingestDocument, searchDocuments } from '../server/documents/pipeline.mjs';

const __dirname = dirname(fileURLToPath(import.meta.url));
const REPO = join(__dirname, '..');
const SERVICE = join(REPO, 'server', 'ocr', 'ocr_service.py');
const FIXTURE_DIR = join(REPO, 'tests', 'fixtures', 'ocr');
const PNG = join(FIXTURE_DIR, 'sample-scan.png');
const PDF = join(FIXTURE_DIR, 'sample-scan.pdf');
const MAKE_FIXTURES = join(REPO, 'scripts', 'make-ocr-fixtures.py');
const PORT = Number(process.env.OCR_TEST_PORT || 8291);

// __REAL_BODY__

/**
 * Pick the interpreter that has PaddleOCR. OCR_PYTHON wins (the operator's override); then
 * the conventional .venv-ocr the spec says already exists; then a bare `python3`. A relative
 * configured path is resolved against the repo so `npm run ocr:test:real` works from anywhere.
 */
function resolvePython() {
  const configured = (process.env.OCR_PYTHON ?? '').trim();
  if (configured) {
    if (!configured.includes('/')) return configured;
    return isAbsolute(configured) ? configured : join(REPO, configured);
  }
  const venv = join(REPO, '.venv-ocr', 'bin', 'python');
  return existsSync(venv) ? venv : 'python3';
}

const PYTHON = resolvePython();

let passed = 0; let failed = 0;
async function check(name, fn) {
  let problem = null;
  try { problem = (await fn()) ?? null; } catch (e) { problem = `threw: ${e.message}`; }
  if (problem) { failed += 1; console.log(`  FAIL  ${name}\n        ${problem}`); }
  else { passed += 1; console.log(`  ok    ${name}`); }
}

/** A real engine won't reproduce text perfectly — compare on normalised, case-folded text. */
function normalise(text) {
  return String(text).toLowerCase().replace(/[^a-z0-9]+/g, ' ').trim();
}
/** How many of `tokens` (each already lower/space-normalised) appear in the recognised text. */
function tokensFound(text, tokens) {
  const hay = normalise(text);
  return tokens.filter((t) => hay.includes(t));
}

/** One POST to the OCR service (used for /ocr/pdf, which the Node adapter does not wrap). */
function postJson(path, body, timeoutMs = 180_000) {
  return new Promise((resolve) => {
    const buf = Buffer.from(JSON.stringify(body));
    const req = http.request(
      { host: '127.0.0.1', port: PORT, path, method: 'POST',
        headers: { 'Content-Type': 'application/json', 'Content-Length': buf.length } },
      (res) => {
        const chunks = [];
        res.on('data', (c) => chunks.push(c));
        res.on('end', () => {
          try { resolve(JSON.parse(Buffer.concat(chunks).toString('utf8'))); }
          catch { resolve({ ok: false, code: 'bad_response' }); }
        });
      },
    );
    const timer = setTimeout(() => req.destroy(new Error('timeout')), timeoutMs);
    req.on('close', () => clearTimeout(timer));
    req.on('error', (e) => resolve({ ok: false, code: 'transport_error', message: e.message }));
    req.write(buf); req.end();
  });
}

function ensureFixtures() {
  if (existsSync(PNG) && existsSync(PDF)) return true;
  console.log('  fixtures missing — generating with', PYTHON, '…');
  const r = spawnSync(PYTHON, [MAKE_FIXTURES], { cwd: REPO, stdio: 'inherit' });
  return r.status === 0 && existsSync(PNG) && existsSync(PDF);
}

// A config whose ocr.* points at OUR service, with a long timeout so a cold model build on
// the very first image does not look like a failure.
const cfg = loadConfig({
  OCR_ENABLED: 'true', OCR_HOST: '127.0.0.1', OCR_PORT: String(PORT), OCR_TIMEOUT_MS: '180000',
});

// __REAL_MAIN__

// --- launch the REAL OCR service (paddle engine) ----------------------------
let child = null;
function shutdown() {
  if (child) { try { child.kill('SIGTERM'); } catch { /* already gone */ } }
}
process.on('exit', shutdown);

async function waitForHealth(timeoutMs) {
  const deadline = Date.now() + timeoutMs;
  let last = null;
  while (Date.now() < deadline) {
    last = await ocrHealth({ cfg, env: process.env });
    if (last.reachable) return last;
    await sleep(300);
  }
  return last;
}

function skip(reason) {
  console.log(`\n  SKIP  real PaddleOCR test — ${reason}`);
  console.log('        (this is expected off-Mac / before `pip install paddleocr`; it is not a pass.)\n');
  shutdown();
  process.exit(0);
}

async function main() {
  console.log('\n  -- real PaddleOCR inference (engine=paddle) -------------------\n');
  console.log(`  python: ${PYTHON}`);

  if (!ensureFixtures()) skip(`could not create fixtures with ${PYTHON} (needs Pillow)`);

  child = spawn(PYTHON, [SERVICE], {
    cwd: REPO,
    env: { ...process.env, OCR_ENGINE: 'paddle', OCR_HOST: '127.0.0.1', OCR_PORT: String(PORT), OCR_ENABLED: 'true' },
    stdio: ['ignore', 'ignore', 'pipe'],
  });
  let serviceLog = '';
  child.stderr.on('data', (d) => { serviceLog += d.toString(); });
  child.on('error', (e) => { serviceLog += `spawn error: ${e.message}\n`; });

  const health = await waitForHealth(15_000);
  if (!health || !health.reachable) skip(`the OCR service did not start with ${PYTHON}\n        ${serviceLog.trim().split('\n').slice(-3).join('\n        ')}`);
  if (health.engine !== 'paddle') skip(`service came up as engine='${health.engine}', not paddle`);
  if (!health.available) skip(`PaddleOCR is not importable under ${PYTHON} — run on the Mac with .venv-ocr`);

  // From here paddle is genuinely available: real assertions, real failures.
  await check('A  /health reports engine=paddle, available, versioned', async () => {
    if (health.engine !== 'paddle') return `engine ${health.engine}`;
    if (health.available !== true) return 'engine not available';
    if (typeof health.paddleocrVersion !== 'string' || health.paddleocrVersion === '') return `no paddleocr version (${health.paddleocrVersion})`;
    console.log(`        paddleocr ${health.paddleocrVersion}, lang ${health.lang}`);
  });

  let pngText = '';
  await check('C  scanned IMAGE: real OCR reads the fixture tokens (sample-scan.png)', async () => {
    const imageBase64 = readFileSync(PNG).toString('base64');
    const r = await ocrImage({ imageBase64, pageNumber: 1, cfg, env: process.env });
    if (!r.ok) return `ocrImage failed: ${r.code} ${r.message}`;
    if (typeof r.confidence !== 'number' || r.confidence <= 0) return `confidence ${r.confidence}`;
    if (!Number.isInteger(r.lineCount) || r.lineCount < 1) return `lineCount ${r.lineCount}`;
    pngText = r.text;
    const want = ['nexora', 'artificial intelligence', 'machine learning', 'neural networks'];
    const hit = tokensFound(r.text, want);
    if (!hit.includes('nexora') || hit.length < 3) {
      return `recognised too few tokens (${hit.length}/4: ${hit.join(', ')})\n        text=${JSON.stringify(r.text)}`;
    }
    console.log(`        recognised ${hit.length}/4 tokens @ confidence ${r.confidence}`);
  });

  await check('D  scanned PDF: /ocr/pdf renders + OCRs every page (both pages read)', async () => {
    const pdfBase64 = readFileSync(PDF).toString('base64');
    const r = await postJson('/ocr/pdf', { pdfBase64, dpi: 150 });
    if (!r.ok) return `pdf OCR failed: ${r.code} ${r.message ?? ''}`;
    if (r.pageCount !== 2 || !Array.isArray(r.pages) || r.pages.length !== 2) return `pageCount ${r.pageCount}`;
    const page1 = tokensFound(r.pages[0].text, ['nexora', 'database management', 'tcp congestion control']);
    const page2 = tokensFound(r.pages[1].text, ['competency based learning', 'neural networks', 'machine learning']);
    if (page1.length < 2) return `page 1 tokens too few (${page1.join(', ')}); text=${JSON.stringify(r.pages[0].text)}`;
    if (page2.length < 2) return `page 2 tokens too few (${page2.join(', ')}); text=${JSON.stringify(r.pages[1].text)}`;
    console.log(`        page1 ${page1.length}/3, page2 ${page2.length}/3 tokens recognised`);
  });

  console.log('\n  -- E  real OCR text flows through the pipeline (mixed doc) ----\n');

  await check('E  ingest OCR text beside a native page -> mixed doc, OCR topic retrievable', async () => {
    if (!pngText || !/neural/i.test(normalise(pngText))) return 'no usable OCR text from test C to feed the pipeline';
    const workdir = mkdtempSync(join(tmpdir(), 'ocr-real-'));
    try {
      const store = await openDocumentStore(workdir);
      const userId = 'ocr-real-user';
      const env = { AI_PROVIDER: 'mock', DATABASE_URL: '' };
      // Page 1: ordinary typed text on an unrelated topic. Page 2: the REAL recognised text,
      // padded to a substantive paragraph so the retriever has real OCR content to rank.
      const nativeText = 'Course logistics and the weekly schedule for administrative announcements. '.repeat(10);
      const ocrParagraph = `${pngText}\n\n`
        + 'Neural networks learn internal representations from raw data through many layers. '
        + 'Machine learning models improve their predictions as they are trained on more examples. '
        + 'Artificial intelligence systems combine these techniques to perform recognition tasks.';
      const pages = [
        { page: 1, text: nativeText, source: 'native_text' },
        { page: 2, text: ocrParagraph, source: 'ocr', confidence: Math.max(0.5, 0.9) },
      ];
      const ing = await ingestDocument({ store, userId, filename: 'real-ocr-mixed.pdf', pages, env });
      if (!ing.ok) return `ingest failed: ${ing.code} ${ing.message}`;
      const doc = store.getDocument(userId, ing.document.id);
      if (doc.extractionMethod !== 'mixed') return `doc.extractionMethod ${doc.extractionMethod}, expected mixed`;
      if (doc.pagesOcred !== 1) return `pagesOcred ${doc.pagesOcred}`;
      const s = await searchDocuments({ store, userId, documentIds: [ing.document.id], query: 'neural networks machine learning', env });
      if (!s.ok) return `search failed: ${s.code}`;
      if (!/neural/i.test(s.retrieval.contextText)) return 'OCR-only topic was not retrieved';
      const ocrChunk = s.retrieval.usedChunks.find((c) => c.pageStart >= 2);
      if (!ocrChunk) return 'no chunk retrieved from the OCR page';
      if (!['ocr', 'mixed'].includes(ocrChunk.extractionMethod)) return `retrieved chunk mislabelled ${ocrChunk.extractionMethod}`;
    } finally {
      rmSync(workdir, { recursive: true, force: true });
    }
  });
}

main().then(() => {
  shutdown();
  console.log(`\n  ${failed === 0 ? 'Real PaddleOCR checks passed.' : 'Real PaddleOCR checks FAILED.'}  ${passed} passed, ${failed} failed\n`);
  process.exit(failed === 0 ? 0 : 1);
}).catch((e) => {
  shutdown();
  console.log(`\n  FAIL  real test threw: ${e.message}\n`);
  process.exit(1);
});


